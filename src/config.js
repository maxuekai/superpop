// 全局游戏常量
// 世界尺寸曾经是 1024×768，实测玩家**68 秒**就能把它吸干净：球直径长到 356，
// 正好等于手机竖屏视口宽度（355），整块屏幕被自己的球占满，视口里只剩球边缘一圈
// 食物，看起来就像"食物长在我身上"（真机反馈过这个现象，但它不是 spawnFood 的 bug——
// spawnFood 的避让一直是好的，实测到 r=260 仍有 100% 找到干净位置）。
//
// 放大到 1280×1280（面积 ×1.33）。为什么是这个形状而不是继续放大——
// ① 世界越大 AI 越抓不到（`npm run sim -- --worldW --worldH` 实测）：
//      1280×960  被吃 18/20      1120×1600 被吃 11/20      1280×1600 被吃 14/20
// ② 手机竖屏的视野上限由**世界高度**决定（长边是竖直方向）。世界越高，
//    "球变大 → 看更远"的有效区间越长：1280×960 只活到 r≈12，1280×1280 能到 r≈27，
//    配合下面 maxZoomOut 的上限能到 r≈58。r≈12 等于完全没有缩放。
// 想要更长的单局应该调 KING.mass（见下），而不是继续放大地图。
// maxBallRadius：单个球的半径上限（= 最小边 × 0.25）。必须有这道保险——
// Ball.update 的边界钳制是 `x = min(max(r, w-r), max(r, x))`，r 一旦超过世界宽度，
// world.width - r 变负，x 就被硬推到界外；而相机视口被 clamp 在世界内，
// 于是球永远在屏幕外、走不回来。实测 r=2589（质量 6.7M）时球心被钉死在 x=2589。
// 正常玩到不了（称王门槛 r=173 就结束），但没有上限就等于留了个死档。
