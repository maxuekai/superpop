// 分裂：一个球可以切成多个「细胞」，同属一个 owner。
// 质量守恒（分裂只是把质量对半分，不凭空产生），同一 owner 的细胞之间不能互吃；
// 冷却结束前不能再分，细胞靠拢到一定距离会自动合并回去。
export const SPLIT = {
    // 半径小于这个值的细胞不能再分（避免切出一堆小渣）
    minCellRadius: 16,
    cooldown: 8, // 两次分裂之间的间隔（秒）
    mergeCooldown: 3, // 分裂后多久才允许重新合并（秒），防止切完立刻粘回去
    mergeFactor: 0.9, // 两细胞中心距 < (r1+r2) × 该值时合并
    maxCells: 8, // 场上最多同时存在多少个自己的细胞
    // 切开后两半各自往旁边让开多少，单位是「切完之后的半径」：初始中心距 = 2 × 该值 × 半径。
    // 原来是 0.35 ×【原半径】：r=16 切完两半各 11.3、半径和 22.6，中心距却只有 11.2
    // —— 视觉上两半直接叠在一起，而且这个距离小于合并阈值 20.4，3 秒后就被吸回一个球。
    // 玩家实测反馈是"分裂也没分裂多远，还是很近"+"按了没反应"。
    // 现在 1.4 → 中心距 31.7（约 1.4 倍半径和）：既不重叠，也不会自动粘回。
    separation: 1.4,
    // 切开的瞬间往外弹一下再停下，纯粹是手感：两半朝同一方向以同一速度走，
    // 距离会永远停在初始间距上，看起来就像球"变胖"而不是"裂开"。
    // 速度线性衰减到 0，单侧总位移 ≈ pushSpeed × pushTime / 2。
    pushSpeed: 120, // 世界单位/秒（会按体型缩放）
    pushTime: 0.3, // 秒
};

